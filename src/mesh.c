#include "mesh.h"

void genCube(Vertex* v, u16* i) {
  float h = 0.5f;

  // ===== FRONT (+Z) =====
  v[0] = (Vertex){{-h, -h, h}, {0, 0, 1}, {0, 0, 0}};
  v[1] = (Vertex){{h, -h, h}, {0, 0, 1}, {1, 0, 0}};
  v[2] = (Vertex){{h, h, h}, {0, 0, 1}, {1, 1, 0}};
  v[3] = (Vertex){{-h, h, h}, {0, 0, 1}, {0, 1, 0}};

  // ===== BACK (-Z) =====
  v[4] = (Vertex){{h, -h, -h}, {0, 0, -1}, {0, 0, 0}};
  v[5] = (Vertex){{-h, -h, -h}, {0, 0, -1}, {1, 0, 0}};
  v[6] = (Vertex){{-h, h, -h}, {0, 0, -1}, {1, 1, 0}};
  v[7] = (Vertex){{h, h, -h}, {0, 0, -1}, {0, 1, 0}};

  // ===== RIGHT (+X) =====
  v[8]  = (Vertex){{h, -h, h}, {1, 0, 0}, {0, 0, 0}};
  v[9]  = (Vertex){{h, -h, -h}, {1, 0, 0}, {1, 0, 0}};
  v[10] = (Vertex){{h, h, -h}, {1, 0, 0}, {1, 1, 0}};
  v[11] = (Vertex){{h, h, h}, {1, 0, 0}, {0, 1, 0}};

  // ===== LEFT (-X) =====
  v[12] = (Vertex){{-h, -h, -h}, {-1, 0, 0}, {0, 0, 0}};
  v[13] = (Vertex){{-h, -h, h}, {-1, 0, 0}, {1, 0, 0}};
  v[14] = (Vertex){{-h, h, h}, {-1, 0, 0}, {1, 1, 0}};
  v[15] = (Vertex){{-h, h, -h}, {-1, 0, 0}, {0, 1, 0}};

  // ===== TOP (+Y) =====
  v[16] = (Vertex){{-h, h, h}, {0, 1, 0}, {0, 0, 0}};
  v[17] = (Vertex){{h, h, h}, {0, 1, 0}, {1, 0, 0}};
  v[18] = (Vertex){{h, h, -h}, {0, 1, 0}, {1, 1, 0}};
  v[19] = (Vertex){{-h, h, -h}, {0, 1, 0}, {0, 1, 0}};

  // ===== BOTTOM (-Y) =====
  v[20] = (Vertex){{-h, -h, -h}, {0, -1, 0}, {0, 0, 0}};
  v[21] = (Vertex){{h, -h, -h}, {0, -1, 0}, {1, 0, 0}};
  v[22] = (Vertex){{h, -h, h}, {0, -1, 0}, {1, 1, 0}};
  v[23] = (Vertex){{-h, -h, h}, {0, -1, 0}, {0, 1, 0}};

  // ===== INDICES =====
  u16 inds[36] = {
      0,  1,  2,  2,  3,  0,  // Front
      4,  5,  6,  6,  7,  4,  // Back
      8,  9,  10, 10, 11, 8,  // Right
      12, 13, 14, 14, 15, 12, // Left
      16, 17, 18, 18, 19, 16, // Top
      20, 21, 22, 22, 23, 20  // Bottom
  };

  for (int k = 0; k < 36; ++k)
    i[k] = inds[k];
}
